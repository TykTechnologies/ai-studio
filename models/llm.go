type Vendor string

type LLM struct {
	gorm.Model
	ID               uint   `json:"id" gorm:"primary_key"`
	Name             string `json:"name"`
	APIKey           string `json:"api_key"`
	APIEndpoint      string `json:"api_endpoint"`
	DefaultModel     string `json:"default_model"`
	PrivacyScore     int    `json:"privacy_score"`
	ShortDescription string `json:"short_description"`
	LongDescription  string `json:"long_description"`
	LogoURL          string `json:"logo"`
	Vendor           Vendor `json:"vendor"`
	Active           bool   `json:"active"`
	// Budget
	MonthlyBudget   *float64   `json:"monthly_budget" gorm:"column:monthly_budget"`
	BudgetStartDate *time.Time `json:"budget_start_date" gorm:"column:budget_start_date"`
	// Hub-and-Spoke Configuration
	Namespace string `json:"namespace" gorm:"default:'';index:idx_llm_namespace"`
	// Body logging control - when true, request/response bodies are NOT stored in proxy logs
	DontLogBodies bool `json:"dont_log_bodies" gorm:"default:false"`

	Filters       []*Filter `json:"filters" gorm:"many2many:llm_filters;"`
	Plugins       []*Plugin `json:"plugins" gorm:"many2many:llm_plugins;"`
	AllowedModels []string  `json:"allowed_models" gorm:"serializer:json"`

	// Plugin-stored metadata
	Metadata JSONMap `json:"metadata" gorm:"type:json"`

	// Failover is the ordered waterfall of (LLM, model) pairs the proxy tries
	// when this LLM's upstream fails. Empty means no failover. Stored via
	// Scanner/Valuer rather than serializer:json because the row is an audit
	// snapshot target and serializer-tagged fields break that map scan.
	Failover LLMFailover `json:"failover" gorm:"type:json"`

	// VendorWorkspaceID pins the vendor workspace every upstream call for
	// this LLM is made in (Anthropic: the anthropic-workspace-id header).
	// The gateway sets it and drops any value a client sends; empty sends
	// none, so calls run in the API key's default workspace.
	VendorWorkspaceID string `json:"vendor_workspace_id" gorm:"size:128"`

	// PriceMultipliers overrides the vendor's price multiplier per service
	// tier for this LLM ({"batch": 0.4}); see LLMPriceMultipliers.
	PriceMultipliers LLMPriceMultipliers `json:"price_multipliers" gorm:"type:json"`

	// TracingContentModeMax caps the agent tracing content mode for calls to
	// this LLM, whatever the App asks for; empty means no cap (Enterprise).
	TracingContentModeMax string `json:"tracing_content_mode_max" gorm:"size:16"`
	// TracingPropagationOptOut stops the gateway sending traceparent to this
	// LLM's upstream; by default it is sent (Q11).
	TracingPropagationOptOut bool `json:"tracing_propagation_opt_out" gorm:"not null;default:false"`

	// Resource signing keys sign the resource IDs native API extensions hand
	// out (see llm_resource_signing.go). Generated by the hub, synced to
	// edges, never serialised, and written only by the dedicated functions
	// (LLM.Update leaves them alone). The secrets are stored as
	// secrets.EncryptValue output.
	ResourceSigningSecret        string     `json:"-" gorm:"type:text"`
	ResourceSigningSecretPrev    string     `json:"-" gorm:"type:text"`
	ResourceSigningPrevExpiresAt *time.Time `json:"-"`
	ResourceSigningRotatedAt     *time.Time `json:"-"`

	// AllowInternalHost is the admin-only "Allow internal host" switch: the
	// LLM's own host(s) may be internal addresses while blocking stays on for
	// everything else (netguard.ExemptionFor). Off by default; never set
	// from a community submission.
	AllowInternalHost bool `json:"allow_internal_host" gorm:"not null;default:false"`
}

